from datetime import date
from typing import Optional

from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
)


# =========================================================
# Create Project
# =========================================================

class ProjectCreate(BaseModel):

    # -----------------------------------------------------
    # Student Profile
    # -----------------------------------------------------

    student_profile_id: int

    # -----------------------------------------------------
    # Project Information
    # -----------------------------------------------------

    title: str = Field(
        ...,
        min_length=1,
        max_length=200
    )

    description: str = Field(
        ...,
        min_length=1
    )

    # -----------------------------------------------------
    # Technologies
    # -----------------------------------------------------

    technologies: Optional[str] = None

    # -----------------------------------------------------
    # Project Links
    # -----------------------------------------------------

    github: Optional[str] = None

    live_demo: Optional[str] = None

    # -----------------------------------------------------
    # Project Image
    # -----------------------------------------------------

    image: Optional[str] = None

    # -----------------------------------------------------
    # Project Dates
    # -----------------------------------------------------

    start_date: Optional[date] = None

    end_date: Optional[date] = None

    # -----------------------------------------------------
    # Currently Working
    # -----------------------------------------------------

    is_current: bool = False


# =========================================================
# Update Project
# =========================================================

class ProjectUpdate(BaseModel):

    # -----------------------------------------------------
    # Project Information
    # -----------------------------------------------------

    title: Optional[str] = Field(
        default=None,
        min_length=1,
        max_length=200
    )

    description: Optional[str] = Field(
        default=None,
        min_length=1
    )

    # -----------------------------------------------------
    # Technologies
    # -----------------------------------------------------

    technologies: Optional[str] = None

    # -----------------------------------------------------
    # Project Links
    # -----------------------------------------------------

    github: Optional[str] = None

    live_demo: Optional[str] = None

    # -----------------------------------------------------
    # Project Image
    # -----------------------------------------------------

    image: Optional[str] = None

    # -----------------------------------------------------
    # Project Dates
    # -----------------------------------------------------

    start_date: Optional[date] = None

    end_date: Optional[date] = None

    # -----------------------------------------------------
    # Currently Working
    # -----------------------------------------------------

    is_current: Optional[bool] = None


# =========================================================
# Project Response
# =========================================================

class ProjectResponse(BaseModel):

    # -----------------------------------------------------
    # Primary Key
    # -----------------------------------------------------

    id: int

    # -----------------------------------------------------
    # Student Profile
    # -----------------------------------------------------

    student_profile_id: int

    # -----------------------------------------------------
    # Project Information
    # -----------------------------------------------------

    title: str

    description: str

    # -----------------------------------------------------
    # Technologies
    # -----------------------------------------------------

    technologies: Optional[str] = None

    # -----------------------------------------------------
    # Project Links
    # -----------------------------------------------------

    github: Optional[str] = None

    live_demo: Optional[str] = None

    # -----------------------------------------------------
    # Project Image
    # -----------------------------------------------------

    image: Optional[str] = None

    # -----------------------------------------------------
    # Project Dates
    # -----------------------------------------------------

    start_date: Optional[date] = None

    end_date: Optional[date] = None

    # -----------------------------------------------------
    # Currently Working
    # -----------------------------------------------------

    is_current: bool

    # -----------------------------------------------------
    # SQLAlchemy → Pydantic
    # -----------------------------------------------------

    model_config = ConfigDict(
        from_attributes=True
    )